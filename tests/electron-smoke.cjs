const { _electron: electron, expect } = require('@playwright/test');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
(async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'folio-ui-'));
  const userData = path.join(root, 'profile');
  await fs.mkdir(userData);
  for (const folder of ['first', 'second']) {
    await fs.mkdir(path.join(root, folder));
    await fs.writeFile(path.join(root, folder, 'note.md'), `# ${folder} のノート\n\n| A | B |\n| - | - |\n| 1 | 2 |\n\n\`\`\`javascript\nconst answer = 42;\n\`\`\`\n\n$$x^2 + y^2 = z^2$$\n\n<script>window.pwned = true</script>\n`);
  }
  let app;
  const launch = async () => {
    app = await electron.launch({ args: [path.resolve('.'), `--user-data-dir=${userData}`], timeout: 30000 });
    const page = await app.firstWindow();
    await page.waitForSelector('.markdown h1');
    return page;
  };
  try {
    let page = await launch();
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await expect(page.locator('.markdown h1')).toHaveText('思考に、余白を。');
    await expect(page.locator('.markdown table')).toHaveCount(1);
    await expect(page.locator('.katex')).toHaveCount(2);
    await expect(page.locator('.hljs-keyword').first()).toBeAttached();
    await page.getByRole('button', { name: 'Raw', exact: true }).click();
    await expect(page.locator('.raw-source')).toContainText('# 思考に、余白を。');
    await expect(page.locator('.raw-source')).toContainText('```javascript');
    await expect(page.locator('.raw-source')).toContainText('$$');
    await expect(page.locator('.markdown')).toHaveCount(0);
    await expect(page.getByRole('button', { name: '目次', exact: true })).toBeDisabled();
    await page.getByRole('button', { name: 'プレビュー', exact: true }).click();
    await expect(page.locator('.markdown h1')).toHaveText('思考に、余白を。');
    await page.getByRole('button', { name: '表示設定' }).click();
    await page.getByRole('button', { name: 'ダーク', exact: true }).click();
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
    await page.getByRole('button', { name: '明朝', exact: true }).click();
    await page.locator('#font-size').fill('19');
    await expect(page.locator('article')).toHaveCSS('font-size', '19px');
    await page.getByRole('button', { name: 'セピア', exact: true }).click();
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'sepia');
    await page.getByRole('button', { name: 'ライト', exact: true }).click();
    await page.getByRole('button', { name: 'ゴシック', exact: true }).click();
    await page.locator('#font-size').fill('16');
    await page.getByRole('button', { name: '設定を閉じる' }).click();
    await page.getByRole('button', { name: '目次', exact: true }).click();
    await page.locator('.outline').getByRole('button', { name: '数式', exact: true }).click();
    await expect(page.locator('.reader')).not.toHaveJSProperty('scrollTop', 0);
    await page.getByRole('button', { name: '目次を閉じる' }).click();
    await page.getByRole('button', { name: 'ページの先頭へ' }).click();
    await page.screenshot({ path: path.resolve('tests/preview.png') });
    await app.evaluate(({ dialog }, files) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: files }); }, [path.join(root, 'first/note.md'), path.join(root, 'second/note.md')]);
    await page.getByRole('button', { name: /ファイルを追加/ }).click();
    await expect(page.locator('.file-row')).toHaveCount(3);
    await expect(page.locator('.markdown h1')).toHaveText('first のノート');
    await expect(page.locator('.katex')).toHaveCount(1);
    if (await page.evaluate(() => window.pwned)) throw new Error('Markdown script was executed');
    await page.getByRole('button', { name: 'コードをコピー' }).click();
    await expect(page.getByText('コピーしました')).toBeVisible();
    await page.getByRole('textbox', { name: 'ファイルを検索' }).fill('second');
    await expect(page.locator('.file-row')).toHaveCount(1);
    await page.locator('.file-select').click();
    await expect(page.locator('.markdown h1')).toHaveText('second のノート');
    await page.getByRole('button', { name: '検索をクリア' }).click();
    await fs.writeFile(path.join(root, 'second/note.md'), '# 更新されました\n\n再読み込み');
    await page.getByRole('button', { name: 'ファイルを再読み込み' }).click();
    await expect(page.locator('.markdown h1')).toHaveText('更新されました');
    await page.getByRole('button', { name: '表示設定' }).click();
    await page.getByRole('button', { name: 'ダーク', exact: true }).click();
    await page.getByRole('button', { name: '等幅', exact: true }).click();
    await page.locator('#font-size').fill('18');
    await app.close();
    page = await launch();
    await expect(page.locator('.file-row')).toHaveCount(3);
    await expect(page.locator('.markdown h1')).toHaveText('更新されました');
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
    await expect(page.locator('article')).toHaveCSS('font-size', '18px');
    await page.locator('.file-row.selected').hover();
    await page.locator('.file-row.selected .remove-file').click();
    await expect(page.locator('.file-row')).toHaveCount(2);
    await fs.access(path.join(root, 'second/note.md'));
    if (errors.length) throw new Error(errors.join('\n'));
    console.log('PASS: Electron rendering, tables, syntax highlighting, math, themes, fonts, outline, file selection, same-named files, search, reload, clipboard, persistence, and removal.');
  } finally { if (app) await app.close().catch(() => {}); await fs.rm(root, { recursive: true, force: true }); }
})().catch(error => { console.error(error); process.exitCode = 1; });
